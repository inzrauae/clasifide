    <h2>When buying</h2>
    <ul>
        <li>Meet the seller in a busy public place, or at their shop. Bring a friend for expensive items.</li>
        <li>Inspect the item before paying. For vehicles, check the CR book, chassis number and revenue licence, and get a mechanic’s opinion.</li>
        <li>For property, check the deeds with a lawyer before paying any deposit.</li>
        <li><b>Never pay in advance</b> for an item you have not seen, and never pay “courier” or “customs” fees to receive a parcel.</li>
    </ul>
    <h2>When selling</h2>
    <ul>
        <li>Confirm the money is in your account before handing over the item. Fake bank SMS messages are common.</li>
        <li>Never share an OTP code. 4U.lk staff will never ask for it.</li>
        <li>Be careful with buyers who offer more than the asking price or want to pay via a third party.</li>
    </ul>
    <h2>Badges you can trust</h2>
    <ul>
        <li><b>VERIFIED</b> – our team checked this seller’s business registration or identity.</li>
        <li><b>MEMBER</b> – the seller has a paid 4U.lk package.</li>
        <li>Seller ratings come only from buyers who actually chatted with the seller.</li>
    </ul>
    <h2>How we protect you</h2>
    <p>Every ad is checked automatically for scam phrases, unrealistic prices, duplicate ads and re-used photos. Suspicious ads are held for review by our team. Ads reported as fraud by several people are taken down until checked.</p>
